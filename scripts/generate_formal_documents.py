from pathlib import Path
import re

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.shared import Cm, Pt


OUT_DIR = Path("docs_final")
FONT = "Times New Roman"


def set_run_font(run, bold=False):
    run.font.name = FONT
    run._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    run._element.rPr.rFonts.set(qn("w:cs"), FONT)
    run.font.size = Pt(14)
    run.bold = bold


def setup_doc(doc):
    section = doc.sections[0]
    section.top_margin = Cm(2)
    section.bottom_margin = Cm(2)
    section.left_margin = Cm(3)
    section.right_margin = Cm(1.5)

    style = doc.styles["Normal"]
    style.font.name = FONT
    style._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    style._element.rPr.rFonts.set(qn("w:cs"), FONT)
    style.font.size = Pt(14)
    style.paragraph_format.line_spacing = 1.5
    style.paragraph_format.space_after = Pt(0)


def is_heading(text):
    return bool(re.match(r"^(\d+(\.\d+)*)\s+\S", text))


def add_text_doc(filename, text):
    doc = Document()
    setup_doc(doc)
    blocks = [b.strip() for b in text.strip().split("\n\n") if b.strip()]
    for index, block in enumerate(blocks):
        p = doc.add_paragraph()
        if index == 0:
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            run = p.add_run(block)
            set_run_font(run, bold=True)
            continue

        first_line = block.splitlines()[0].strip()
        if is_heading(first_line):
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT
            run = p.add_run(block)
            set_run_font(run, bold=True)
        else:
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT
            run = p.add_run(block)
            set_run_font(run)

    OUT_DIR.mkdir(exist_ok=True)
    doc.save(OUT_DIR / filename)
    print(OUT_DIR / filename)


